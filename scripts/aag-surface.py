#!/usr/bin/env python3
"""Generate and manage individually owned, user-scoped agent integrations."""
import argparse
from contextlib import contextmanager
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import sys
import tempfile

NAME = re.compile(r"aag-surface-[a-z0-9]+(?:-[a-z0-9]+)*\Z")
STATE = "aag-surface-install.json"


class SurfaceError(Exception):
    pass


def exists(path):
    return path.exists() or path.is_symlink()


def require_name(name):
    if not NAME.fullmatch(name) or len(name) > 64:
        raise SurfaceError(f"Invalid surface name: {name}")


def regular_tree(path):
    """Reject links/special files before reading or replacing owned content."""
    if path.is_symlink():
        raise SurfaceError(f"Symlink is not an owned copy: {path}")
    if path.is_dir():
        for child in path.iterdir():
            regular_tree(child)
    elif not path.is_file():
        raise SurfaceError(f"Expected regular file or directory: {path}")


def files(path):
    regular_tree(path)
    return {p.relative_to(path).as_posix(): p.read_bytes()
            for p in sorted(path.rglob("*")) if p.is_file()}


def frontmatter(path, fields, optional=()):
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise SurfaceError(f"Missing frontmatter: {path}")
    header, body = text[4:].split("\n---\n", 1)
    data = {}
    for line in header.splitlines():
        key, sep, value = line.partition(":")
        if not sep or key not in (*fields, *optional) or key in data or not value.strip():
            raise SurfaceError(f"Invalid frontmatter field in {path}: {line}")
        value = value.strip()
        data[key] = json.loads(value) if value.startswith('"') else value
        if not isinstance(data[key], str) or "\n" in data[key]:
            raise SurfaceError(f"Expected one-line text for {key}: {path}")
    if not set(fields).issubset(data) or not body.strip():
        raise SurfaceError(f"Expected fields {fields} and a body: {path}")
    require_name(data["name"])
    return data, body.rstrip() + "\n"


def quoted(value):
    """A double-quoted scalar valid in both native YAML and TOML."""
    encoded = json.dumps(value, ensure_ascii=False)
    # YAML normalizes some literal Unicode line breaks; TOML rejects raw DEL.
    return re.sub(r"[\x7f-\x9f\u2028\u2029]",
                  lambda match: f"\\u{ord(match[0]):04x}", encoded)


def render(source):
    canonical = source / "canonical"
    regular_tree(canonical)
    result = {}
    codex_rules = []
    for path in sorted((canonical / "rules").glob("*.md")):
        require_name(path.stem)
        body = path.read_text(encoding="utf-8").rstrip() + "\n"
        if not body.startswith("# ") or len(body.splitlines()) < 3:
            raise SurfaceError(f"Rule needs a title and body: {path}")
        title = body.splitlines()[0][2:]
        result[f"cursor/aag-surface/rules/{path.stem}.mdc"] = (
            f"---\ndescription: {quoted(title)}\nalwaysApply: true\n---\n{body}"
        ).encode()
        codex_rules.append(body)
    if not codex_rules:
        raise SurfaceError("At least one canonical rule is required")
    result["codex/AGENTS.md"] = (
        "<!-- Generated by aag-surface; edit canonical/rules. -->\n\n" + "\n".join(codex_rules)
    ).encode()
    if len(result["codex/AGENTS.md"]) > 32768:
        raise SurfaceError("Generated AGENTS.md exceeds Codex's default 32 KiB instruction budget")
    for skill in sorted((canonical / "skills").iterdir()):
        if not skill.is_dir():
            raise SurfaceError(f"Expected skill directory: {skill}")
        require_name(skill.name)
        data, body = frontmatter(skill / "SKILL.md", ("name", "description"), ("invocation",))
        if data["name"] != skill.name:
            raise SurfaceError(f"Skill name must match its directory: {skill}")
        invocation = data.get("invocation", "auto")
        if invocation not in ("auto", "explicit"):
            raise SurfaceError(f"Skill invocation must be auto or explicit: {skill}")
        resources = files(skill)
        if invocation == "explicit" and "agents/openai.yaml" in resources:
            raise SurfaceError(f"agents/openai.yaml is generated for explicit invocation: {skill}")
        # Cursor also imports Codex skills, so both copies carry its native flag.
        invocation_header = "disable-model-invocation: true\n" if invocation == "explicit" else ""
        for relative, content in resources.items():
            if relative == "SKILL.md":
                content = (f"---\nname: {quoted(data['name'])}\n"
                           f"description: {quoted(data['description'])}\n"
                           f"{invocation_header}---\n{body}").encode()
            result[f"codex/skills/{skill.name}/{relative}"] = content
            result[f"cursor/aag-surface/skills/{skill.name}/{relative}"] = content
        if invocation == "explicit":
            result[f"codex/skills/{skill.name}/agents/openai.yaml"] = (
                b"policy:\n  allow_implicit_invocation: false\n"
            )
    for path in sorted((canonical / "agents").glob("*.md")):
        data, body = frontmatter(path, ("name", "description", "access"))
        if data["name"] != path.stem or data["access"] not in ("read-only", "inherit"):
            raise SurfaceError(f"Agent filename or access invalid: {path}")
        readonly = data["access"] == "read-only"
        instructions = body
        if readonly:
            instructions += "\nDo not modify files or perform write operations. This is an instruction; permissions are inherited from the parent session.\n"
        result[f"codex/agents/{path.stem}.toml"] = (
            f"name = {quoted(data['name'])}\n"
            f"description = {quoted(data['description'])}\n"
            f"developer_instructions = {quoted(instructions)}\n"
        ).encode()
        result[f"cursor/aag-surface/agents/{path.stem}.md"] = (
            f"---\nname: {data['name']}\ndescription: {quoted(data['description'])}\n"
            f"readonly: {str(readonly).lower()}\n---\n{body}"
        ).encode()
    result["cursor/aag-surface/.cursor-plugin/plugin.json"] = (
        json.dumps({"name": "aag-surface", "version": "0.1.0",
                    "description": "User-scoped rules, skills, and agents generated from aag-surface."},
                   indent=2) + "\n"
    ).encode()
    return result


def check(source):
    expected = render(source)
    output = source / "generated"
    actual = files(output) if exists(output) else {}
    if actual != expected:
        changed = sorted(k for k in actual.keys() | expected.keys() if actual.get(k) != expected.get(k))
        raise SurfaceError("Generated output is stale; run sync: " + ", ".join(changed))
    return expected


def sync(source):
    expected = render(source)
    output = source / "generated"
    if exists(output):
        regular_tree(output)
        if files(output) == expected:
            return
    with tempfile.TemporaryDirectory(prefix=".aag-surface-generation-", dir=source) as temp:
        stage = Path(temp) / "new"
        stage.mkdir()
        for relative, content in expected.items():
            path = stage / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        backup = Path(temp) / "old"
        if exists(output):
            os.replace(output, backup)
        try:
            os.replace(stage, output)
        except BaseException:
            if exists(backup):
                os.replace(backup, output)
            raise


def desired(source):
    check(source)
    result = {".codex/AGENTS.md": source / "generated/codex/AGENTS.md",
              ".cursor/plugins/local/aag-surface": source / "generated/cursor/aag-surface"}
    for path in sorted((source / "generated/codex/skills").glob("*")):
        result[f".codex/skills/{path.name}"] = path
    for path in sorted((source / "generated/codex/agents").glob("*.toml")):
        result[f".codex/agents/{path.name}"] = path
    return result


def allowed_entry(relative):
    if relative == ".codex/AGENTS.md":
        return "file"
    if relative == ".cursor/plugins/local/aag-surface":
        return "directory"
    path = Path(relative)
    if len(path.parts) == 3 and path.parts[:2] == (".codex", "skills"):
        require_name(path.name)
        return "directory"
    if len(path.parts) == 3 and path.parts[:2] == (".codex", "agents") and path.suffix == ".toml":
        require_name(path.stem)
        return "file"
    raise SurfaceError(f"Manifest contains an unowned path: {relative}")


def manifest(source, home):
    if (source / "state").is_symlink():
        raise SurfaceError(f"Unsafe state directory: {source / 'state'}")
    path = source / "state" / STATE
    if not exists(path):
        return {"version": 1, "source": str(source), "home": str(home), "entries": {}}
    regular_tree(path)
    data = json.loads(path.read_text())
    if (not isinstance(data, dict) or data.get("version") != 1 or
            data.get("source") != str(source) or data.get("home") != str(home) or
            not isinstance(data.get("entries"), dict)):
        raise SurfaceError("Install manifest does not belong to this source and target home")
    for relative, details in data["entries"].items():
        kind = allowed_entry(relative)
        if not isinstance(details, dict) or details.get("kind") != kind or not isinstance(details.get("digest"), str):
            raise SurfaceError(f"Invalid ownership entry: {relative}")
    return data


def parents_safe(home, destination):
    current = home
    if not home.is_dir() or home.is_symlink():
        raise SurfaceError(f"Home must be an existing real directory: {home}")
    for part in destination.relative_to(home).parts[:-1]:
        current /= part
        if current.is_symlink() or (exists(current) and not current.is_dir()):
            raise SurfaceError(f"Unsafe shared parent: {current}")


def preflight(home, entries, owned):
    for relative in sorted(set(entries) | set(owned)):
        kind = allowed_entry(relative)
        target = home / relative
        parents_safe(home, target)
        if exists(target):
            if relative not in owned:
                raise SurfaceError(f"Unowned destination already exists: {target}")
            regular_tree(target)
            if target.is_dir() != (kind == "directory"):
                raise SurfaceError(f"Owned destination changed type: {target}")


def fingerprint(path):
    regular_tree(path)
    digest = hashlib.sha256()
    contents = files(path) if path.is_dir() else {"": path.read_bytes()}
    for relative, content in contents.items():
        digest.update(relative.encode() + b"\0" + str(len(content)).encode() + b"\0" + content)
    return {"kind": "directory" if path.is_dir() else "file", "digest": digest.hexdigest()}


def remove(path):
    if path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)
    else:
        path.unlink(missing_ok=True)


def copy(source, target):
    if source.is_dir():
        shutil.copytree(source, target)
    else:
        shutil.copy2(source, target)


def apply_changes(source, home, entries, prior):
    """Stage all copies, then replace entries; undo ordinary failures in reverse."""
    preflight(home, entries, prior["entries"])
    transactions = []
    created_parents = []
    committed = False
    rollback_failed = False
    state_temp = None
    try:
        for relative in sorted(set(entries) | set(prior["entries"])):
            target = home / relative
            missing = []
            parent = target.parent
            while not parent.exists():
                missing.append(parent)
                parent = parent.parent
            for parent in reversed(missing):
                parent.mkdir()
                created_parents.append(parent)
            temp = Path(tempfile.mkdtemp(prefix=".aag-surface-", dir=target.parent))
            operation = {"target": target, "temp": temp, "backed_up": False, "installed": False}
            transactions.append(operation)
            if relative in entries:
                copy(entries[relative], temp / "new")
        for operation in transactions:
            target, temp = operation["target"], operation["temp"]
            if exists(target):
                os.replace(target, temp / "old")
                operation["backed_up"] = True
            if exists(temp / "new"):
                os.replace(temp / "new", target)
                operation["installed"] = True
        state = dict(prior, entries={relative: fingerprint(home / relative) for relative in sorted(entries)})
        state_dir = source / "state"
        state_dir.mkdir(exist_ok=True)
        with tempfile.NamedTemporaryFile(mode="w", prefix=".aag-surface-", dir=state_dir, delete=False) as handle:
            state_temp = Path(handle.name)
            json.dump(state, handle, indent=2)
            handle.write("\n")
        os.replace(state_temp, state_dir / STATE)
        committed = True
    except BaseException as original:
        failures = []
        for operation in reversed(transactions):
            target, temp = operation["target"], operation["temp"]
            try:
                if operation["installed"]:
                    remove(target)
                if operation["backed_up"]:
                    os.replace(temp / "old", target)
            except OSError as error:
                failures.append(f"{target}: {error}; recovery data: {temp}")
        if failures:
            rollback_failed = True
            raise SurfaceError("Rollback incomplete; preserve recovery directories. " + "; ".join(failures)) from original
        raise
    finally:
        if state_temp is not None:
            state_temp.unlink(missing_ok=True)
        if not rollback_failed:
            for operation in transactions:
                shutil.rmtree(operation["temp"])
        if not committed and not rollback_failed:
            for parent in reversed(created_parents):
                parent.rmdir()


def install(source, home):
    apply_changes(source, home, desired(source), manifest(source, home))


def uninstall(source, home):
    prior = manifest(source, home)
    if prior["entries"]:
        apply_changes(source, home, {}, prior)
    (source / "state" / STATE).unlink(missing_ok=True)


def status(source, home):
    prior = manifest(source, home)
    entries = prior["entries"]
    problems = []
    for relative, detail in entries.items():
        target = home / relative
        parents_safe(home, target)
        if not exists(target) or fingerprint(target) != detail:
            problems.append(relative)
    return {"source": str(source), "home": str(home),
            "installation": "installed" if entries else "not installed",
            "owned_entries": len(entries), "missing_or_changed": problems,
            "runtime_verification": "incomplete: Cursor plugin/native skill duplication unresolved"}


@contextmanager
def lock(source):
    directory = source / "state"
    if directory.is_symlink() or (exists(directory) and not directory.is_dir()):
        raise SurfaceError(f"Unsafe state directory: {directory}")
    directory.mkdir(exist_ok=True)
    path = directory / "aag-surface.lock"
    if path.is_symlink():
        raise SurfaceError(f"Unsafe lock: {path}")
    with path.open("a+") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        yield


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    generate = commands.add_parser("sync", help="regenerate both product outputs")
    generate.add_argument("--check", action="store_true")
    commands.add_parser("validate", help="validate canonical sources and generated consistency")
    for name in ("install", "uninstall", "status"):
        command = commands.add_parser(name)
        command.add_argument("--fixture-home", type=Path, help="test-only home under the system temporary directory")
    args = parser.parse_args()
    source = Path(__file__).resolve().parents[1]
    home = Path.home()
    fixture = getattr(args, "fixture_home", None)
    if fixture is not None:
        home = fixture.absolute()
        temp = Path(tempfile.gettempdir()).resolve()
        if home.is_symlink() or home != home.resolve() or not home.is_relative_to(temp) or home == temp:
            raise SurfaceError("Fixture home must be a real descendant of the system temporary directory")
    if args.command == "status":
        print(json.dumps(status(source, home), indent=2))
    elif args.command == "validate" or (args.command == "sync" and args.check):
        check(source)
        print("Canonical and generated content are consistent; client runtime loading is not verified.")
    else:
        with lock(source):
            if args.command == "sync":
                sync(source)
            elif args.command == "install":
                install(source, home)
            else:
                uninstall(source, home)
        print(f"{args.command}: complete" + (" (fixture only)" if fixture else ""))


if __name__ == "__main__":
    try:
        main()
    except (SurfaceError, OSError, ValueError) as error:
        print(f"aag-surface: {error}", file=sys.stderr)
        sys.exit(1)
